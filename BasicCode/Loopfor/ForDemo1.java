package com.DYX.loopfor;

public class ForDemo1 {
    public static void main(String[] args) {
        /*
            for循环
                for(初始化;条件;更新)
                {
                    循环体
                }
        */

        //1.定义变量记录起始值
        int start = 1;
        //2.定义变量记录结束值
        int end = 10;
        //3.定义变量记录和
        int sum = 0;
        //4.循环求和
        for(int i = start; i <= end; i++)
        {
            System.out.println("游戏人物跳跃");
        }
    }
}
